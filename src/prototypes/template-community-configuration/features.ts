function copy<T>(value: T): T {
  return JSON.parse(JSON.stringify(value)) as T
}

/**
 * Where the saved configuration is kept in the browser. The key includes the
 * dashboard's route, so each copy of this template keeps its own.
 */
const STORAGE_KEY = `protowiki:${COMMUNITY_CONFIGURATION_PATH}:community-configuration:v1`

/** The defaults, with any saved configuration over them. */
function load(): Record<string, Record<string, unknown>> {
  const configs = Object.fromEntries(
    FEATURES.map((feature) => [feature.id, copy(feature.defaults)]),
  )
  try {
    const stored = JSON.parse(localStorage.getItem(STORAGE_KEY) ?? '{}')
    for (const id of Object.keys(configs)) {
      if (stored?.[id]) configs[id] = { ...configs[id], ...stored[id] }
    }
  } catch {
    // No storage: the defaults apply.
  }
  return configs
}

function persist(): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(savedConfigs))
  } catch {
    // No storage: the configuration lasts until the page reloads.
  }
}

/** Each feature's saved configuration, by id. It is kept in this browser. */
export const savedConfigs = reactive<Record<string, Record<string, unknown>>>(load())

// A save in another tab updates this one, e.g. the prototype open beside its settings.
window.addEventListener('storage', (event) => {
  if (event.key === STORAGE_KEY) Object.assign(savedConfigs, load())
})

/** A copy of a feature's saved configuration, for its form to edit. */
export function draftConfig(id: string): Record<string, unknown> {
  return copy(savedConfigs[id])
}

export function saveConfig(id: string, config: Record<string, unknown>): void {
  savedConfigs[id] = copy(config)
  persist()
}

/** Discards a feature's saved configuration: its defaults apply again. */
export function resetConfig(id: string): void {
  const feature = FEATURES.find((candidate) => candidate.id === id)
  if (!feature) return
  savedConfigs[id] = copy(feature.defaults)
  persist()
}

/**
 * A feature's saved configuration, for the prototype to read. It updates when
 * someone saves the feature's form, e.g. `useFeatureConfig('Babel').value.BabelAutoCreate`.
 */
export function useFeatureConfig<T = Record<string, unknown>>(id: string) {
  return computed(() => savedConfigs[id] as T)
}
