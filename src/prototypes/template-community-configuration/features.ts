/**
 * The dashboard's own route (file-based: this folder's `index.vue`). In a copy
 * of this folder, change it to the copy's route. The pages find their route
 * from the URL, but the saved configuration is stored under this name, and the
 * prototype links to its settings with it.
 */
export const COMMUNITY_CONFIGURATION_PATH = '/template-community-configuration'

/**
 * The dashboard's route, from the current one: the dashboard itself, or a
 * feature's editor page below it. Links follow it, so a copy of this folder
 * works before `COMMUNITY_CONFIGURATION_PATH` changes.
 */
export function useCommunityConfigurationPath() {
  const route = useRoute()
  const path = computed(() => {
    const current = route.path.replace(/\/$/, '')
    const params = route.params as { feature?: string | string[] }
    return params.feature ? current.replace(/\/[^/]*$/, '') : current
  })
  if (import.meta.env.DEV && path.value !== COMMUNITY_CONFIGURATION_PATH) {
    console.warn(
      `Community Configuration: set COMMUNITY_CONFIGURATION_PATH in features.ts to '${path.value}'.`,
    )
  }
  return path
}

